const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'../Resources/PlaintextWeb/app.js'),'utf8');
let now=100,selected=-1;
const pickerSelection={entries:['Alpha','Alpine','Beta','Bravo','Éclair'].map(name=>({name})),typeaheadPrefix:'',typeaheadLastUpdated:0};
const context=vm.createContext({pickerSelection,Date:{now:()=>now},pickerSelectedIndex:()=>selected,selectPickerIndex:index=>{selected=index;}});
vm.runInContext(source.slice(source.indexOf('function resetTypeahead()'),source.indexOf("document.addEventListener('keydown',event=>{",source.indexOf('function resetTypeahead()'))),context);
context.handleTypeahead('A');assert.equal(selected,0);
context.handleTypeahead('l');context.handleTypeahead('p');context.handleTypeahead('i');assert.equal(selected,1);
now+=1001;context.handleTypeahead('b');assert.equal(selected,2);
context.handleTypeahead('b');assert.equal(selected,3);
context.handleTypeahead('b');assert.equal(selected,2);
context.handleTypeahead('z');assert.equal(selected,2);
context.resetTypeahead();context.handleTypeahead('É');assert.equal(selected,4);
for(const key of ['Enter','ArrowDown','\n','\u007f'])assert.equal(context.typeaheadText(key),null);
assert.equal(context.typeaheadText('é'),'é');
assert.equal(context.typeaheadText('😀'),'😀');
console.log('PASS picker prefixes, timeout, repeated-letter cycling, no match, Unicode, and control keys');
